/*
 * ============================================================================
 * LED驱动实现文件 - dri_led_gpio.c
 * ============================================================================
 * 
 * 本文件实现了LED的底层GPIO操作。
 * 
 * 【STM32 GPIO操作原理】
 * ---------------------------------------------------------------------------
 * STM32的每个GPIO端口（GPIOA~GPIOG）有多个寄存器：
 * 
 * 1. ODR (Output Data Register) - 输出数据寄存器
 *    每个位控制一个引脚的输出电平。
 *    设置某位为1 -> 引脚输出高电平
 *    设置某位为0 -> 引脚输出低电平
 * 
 *    本开发板LED是低电平点亮（LED负极接引脚，正极通过电阻接VCC）
 *    所以：输出0 -> LED亮，输出1 -> LED灭
 * 
 * 2. CRL/CRH - 配置寄存器低/高32位
 *    控制引脚的工作模式（输入/输出，推挽/开漏等）
 *    每个引脚占4位：2位模式(MODE) + 2位配置(CNF)
 *    引脚0-7 用 CRL，引脚8-15 用 CRH
 * 
 * 3. RCC->APB2ENR - 时钟使能寄存器
 *    STM32为了省电，外设默认关闭时钟
 *    使用前必须先开启时钟，否则寄存器操作无效！
 *    GPIOB, GPIOE 属于 APB2 总线，所以需要设置 APB2ENR
 * ============================================================================
 */

#include "dri_led_gpio.h"

/* ---------------------------------------------------------------------------
 * LED映射表定义（核心配置）
 * ---------------------------------------------------------------------------
 * 这里定义了每个LED对应的硬件连接。
 * 
 * led_map[0] = {GPIOB, (1 << 5)}
 *              GPIOB   -> LED1连接在GPIOB端口
 *              (1 << 5) -> 第5个引脚，1左移5位 = 0b000100000 = 0x20
 * 
 * led_map[1] = {GPIOE, (1 << 5)}
 *              GPIOE   -> LED2连接在GPIOE端口
 *              (1 << 5) -> 同样是第5个引脚
 * 
 * const 关键字表示这是只读数据，编译器会放在Flash中而不是RAM中。
 * 如果开发板有更多LED，只需在这里继续添加即可。
 * ---------------------------------------------------------------------------
 */
const LedConfig_t led_map[LED_NUM_MAX] = {
    {GPIOB, (1 << 5)},  // LED1 - 连接在PB5引脚
    {GPIOE, (1 << 5)}   // LED2 - 连接在PE5引脚
};

/*
 * ============================================================================
 * LED GPIO初始化函数
 * ============================================================================
 * 执行三个步骤：
 *   1. 开启GPIO时钟（没有时钟，后续配置无效）
 *   2. 配置引脚模式（推挽输出，50MHz速度）
 *   3. （可选）设置初始电平
 * 
 * 【STM32初始化流程 - 重要概念】
 * ---------------------------------------------------------------------------
 * 第1步：开启时钟
 *   RCC->APB2ENR |= RCC_APB2ENR_IOPBEN;
 *   |= 是按位或运算，只设置对应位为1，不影响其他位
 *   IOPBEN = GPIO B clock ENable，开启GPIOB的时钟
 *   IOPEEN = GPIO E clock ENable，开启GPIOE的时钟
 * 
 * 第2步：配置引脚模式（以PB5为例）
 *   PB5是低8位引脚，使用CRL寄存器配置。
 *   每个引脚占4位：[CNF[1:0]] [MODE[1:0]]
 *   引脚5对应的是 MODE5[1:0] 和 CNF5[1:0]
 * 
 *   GPIOB->CRL &= ~GPIO_CRL_MODE5;  // 清除MODE5的2位（设为00）
 *   GPIOB->CRL |= GPIO_CRL_MODE5_1; // 设置MODE5 = 01（50MHz输出）
 *   GPIOB->CRL &= ~GPIO_CRL_CNF5;   // 设置CNF5 = 00（推挽输出）
 * 
 *   MODE = 01 表示输出模式，最大50MHz
 *   CNF = 00 表示推挽输出（驱动能力强，适合驱动LED）
 * ============================================================================
 */
void DRI_LED_GPIO_Init(void)
{
    /* =========================================================================
     * 第1步：开启GPIOB和GPIOE的时钟
     * =========================================================================
     * STM32上电后，所有外设时钟默认关闭（为了省电）
     * 必须先开启时钟，才能对该外设的寄存器进行操作
     * 
     * RCC (Reset and Clock Control) - 复位和时钟控制器
     * APB2ENR (APB2 Enable Register) - APB2总线外设时钟使能寄存器
     * 
     * GPIOA~GIOG都属于APB2总线，所以用APB2ENR来开启时钟
     * 
     * |= 操作说明：
     *   RCC->APB2ENR |= RCC_APB2ENR_IOPBEN;
     *   等价于：RCC->APB2ENR = RCC->APB2ENR | RCC_APB2ENR_IOPBEN;
     *   只将IOPBEN对应的位置1，其他位保持不变
     */
    RCC->APB2ENR |= RCC_APB2ENR_IOPBEN; // 使能GPIOB时钟（操作GPIOB前必须执行）
    RCC->APB2ENR |= RCC_APB2ENR_IOPEEN; // 使能GPIOE时钟（操作GPIOE前必须执行）
    
    /* =========================================================================
     * 第2步：配置PB5为推挽输出模式
     * =========================================================================
     * PB5属于低8位引脚(0-7)，使用CRL(Configuration Register Low)配置
     * 
     * 每个引脚在CRL中占4位，引脚5的位域：
     *   bit[23:22] = CNF5  (配置位)
     *   bit[21:20] = MODE5 (模式位)
     * 
     * 推挽输出模式设置：
     *   MODE5 = 01 (输出模式，50MHz)
     *   CNF5  = 00 (推挽输出)
     * 
     * 配置步骤（先清后设，防止误操作）：
     */
    GPIOB->CRL &= ~GPIO_CRL_MODE5;  // 清除MODE5位（准备设置为新值）
    GPIOB->CRL |= GPIO_CRL_MODE5_1; // 设置MODE5 = 01（输出模式，50MHz）
    GPIOB->CRL &= ~GPIO_CRL_CNF5;   // 清除CNF5位 = 00（推挽输出模式）
    
    /* =========================================================================
     * 第3步：配置PE5为推挽输出模式
     * （与PB5配置完全相同，只是操作GPIOE）
     */
    GPIOE->CRL &= ~GPIO_CRL_MODE5;  // 清除MODE5位
    GPIOE->CRL |= GPIO_CRL_MODE5_1; // 设置MODE5 = 01（输出模式，50MHz）
    GPIOE->CRL &= ~GPIO_CRL_CNF5;   // 清除CNF5位 = 00（推挽输出模式）
    
    /* =========================================================================
     * （可选）设置初始输出电平
     * =========================================================================
     * 这段代码被注释掉了，因为初始化后会调用 inf_led_close_all() 来关灯
     * 
     * 如果取消注释，PB5和PE5会输出低电平(0)，LED会点亮。
     * 但我们希望初始状态是所有LED关闭，所以不执行这段代码。
     */
    /*
    // 设置PB5和PE5输出低电平（点亮LED）
    GPIOB->ODR &= ~GPIO_ODR_ODR5; // PB5输出0
    GPIOE->ODR &= ~GPIO_ODR_ODR5; // PE5输出0
    */
    
}