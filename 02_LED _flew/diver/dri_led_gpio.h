/*
 * ============================================================================
 * LED驱动头文件 - dri_led_gpio.h
 * ============================================================================
 * 
 * 本文件定义了LED驱动的核心数据类型和接口。
 * 
 * 【核心设计思路】映射表模式
 * ---------------------------------------------------------------------------
 * 老师的代码直接把LED绑定在GPIOA上，但我们的开发板LED连接在GPIOB和GPIOE上。
 * 如果直接改GPIOA为GPIOB/GPIOE，代码会很混乱(因为两个LED在不同端口)。
 * 
 * 所以我们采用"映射表"方案：
 *   1. 用枚举(LedNum_t)给每个LED编号(0, 1, 2...)
 *   2. 用结构体(LedConfig_t)记录每个LED对应的GPIO端口和引脚
 *   3. 用数组(led_map)把所有LED的配置组织起来
 *   4. 操作时：led_map[编号] 就能找到对应的GPIO端口和引脚
 * 
 * 好处：
 *   - 新增LED只需在led_map中添加一项，不需要改其他代码
 *   - 支持LED分散在不同GPIO端口上
 *   - 代码更清晰，硬件配置和逻辑分离
 * 
 * 【为什么用枚举而不是直接位掩码？】
 *   - 枚举有类型安全，编译器会检查参数是否正确
 *   - LED编号(0,1,2)和实际引脚(如第5位)解耦，更灵活
 *   - LED_NUM_MAX自动记录LED总数，方便循环遍历
 * ============================================================================
 */

#ifndef __DRI_LED_GPIO_H__
#define __DRI_LED_GPIO_H__

#include <stm32f10x.h>

/* ---------------------------------------------------------------------------
 * LED编号枚举类型
 * ---------------------------------------------------------------------------
 * 每个枚举值代表一个LED的编号，用于索引led_map数组。
 * 
 * LED_NUM_1 = 0  -> led_map[0] 存储LED1的配置(PB5)
 * LED_NUM_2 = 1  -> led_map[1] 存储LED2的配置(PE5)
 * LED_NUM_MAX = 2 -> 自动记录总共有2个LED，用于循环边界
 * 
 * 注意：枚举值会自动递增，LED_NUM_2 = 1, LED_NUM_MAX = 2
 */
typedef enum {
    LED_NUM_1 = 0,  // LED1编号，对应开发板PB5引脚
    LED_NUM_2,      // LED2编号，对应开发板PE5引脚（自动等于1）
    LED_NUM_MAX     // LED总数，不是实际的LED编号（自动等于2）
} LedNum_t;

/* ---------------------------------------------------------------------------
 * LED配置结构体
 * ---------------------------------------------------------------------------
 * 每个LED需要两个信息：
 *   1. port  - GPIO端口指针（如GPIOB, GPIOE）
 *              STM32的GPIO端口在内存中是连续的，可以用指针访问
 *   2. pin   - 引脚位掩码（如 1<<5 = 0b000100000，表示第5位）
 *              用于操作ODR寄存器的对应位
 * 
 * 示例：
 *   LED1 -> {GPIOB, (1<<5)}  表示操作 GPIOB->ODR 的第5位
 *   LED2 -> {GPIOE, (1<<5)}  表示操作 GPIOE->ODR 的第5位
 */
typedef struct {
    GPIO_TypeDef* port;   // GPIO端口指针（指向GPIOB, GPIOE等）
    uint16_t pin;         // 引脚位掩码（1左移引脚号，如 1<<5）
} LedConfig_t;

/* ---------------------------------------------------------------------------
 * LED映射表声明
 * ---------------------------------------------------------------------------
 * 这是一个常量数组，存储所有LED的硬件配置。
 * extern 关键字表示：数组的定义在其他.c文件中（实际在dri_led_gpio.c中）
 * 
 * 数组长度 = LED_NUM_MAX = 2
 * 索引 0 -> LED1的配置
 * 索引 1 -> LED2的配置
 */
extern const LedConfig_t led_map[LED_NUM_MAX];

/* ---------------------------------------------------------------------------
 * LED编号宏定义
 * ---------------------------------------------------------------------------
 * 为了方便使用，定义LED1/LED2宏，直接对应枚举值。
 * 这样调用 inf_led_open(LED1) 时，实际传入的是 LED_NUM_1 (=0)
 */
#define LED1 LED_NUM_1  // LED1编号，展开后等于 LED_NUM_1 (0)
#define LED2 LED_NUM_2  // LED2编号，展开后等于 LED_NUM_2 (1)

/* ---------------------------------------------------------------------------
 * LED GPIO初始化函数声明
 * ---------------------------------------------------------------------------
 * 配置PB5和PE5为推挽输出模式，开启时钟。
 * 详细实现在 dri_led_gpio.c 中。
 */
void DRI_LED_GPIO_Init(void);

#endif /* __DRI_LED_GPIO_H__ */
