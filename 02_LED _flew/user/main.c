/*
 * ============================================================================
 * 主程序 - LED流水灯
 * ============================================================================
 *
 * 【程序功能】
 *   让开发板上的两个LED灯依次亮灭，形成"流水灯"效果。
 *   运行效果：LED1亮 -> 0.5秒后LED1灭 -> LED2亮 -> 0.5秒后LED2灭 -> 循环
 *
 * 【硬件连接】
 *   LED1 连接在 PB5 引脚（GPIOB端口第5脚）
 *   LED2 连接在 PE5 引脚（GPIOE端口第5脚）
 *   注意：开发板LED是低电平点亮（引脚输出0 = LED亮，输出1 = LED灭）
 *
 * 【文件依赖关系】
 *   main.c  -->  inf_led.h  -->  dri_led_gpio.h  -->  stm32f10x.h
 *           \->  common_delay.h
 *
 * 【学习要点】
 *   1. 分层架构：应用层 -> 接口层 -> 驱动层
 *   2. 数组遍历：用for循环依次操作每个LED
 *   3. 延时函数：让灯亮/灭一段时间，人眼才能看到变化
 *   4. 无限循环：嵌入式程序通常不会结束，while(1)让程序一直运行
 * ============================================================================
 */

#include <stdint.h>		  // 标准整数类型定义（uint8_t, uint16_t, uint32_t等）
#include <stm32f10x.h>	  // STM32F10x系列芯片的寄存器定义（GPIO、RCC等）
#include "inf_led.h"	  // LED接口层头文件（提供inf_led_open/close等函数）
#include "common_delay.h" // 通用延时函数头文件（提供common_delay_ms延时函数）

/*
 * ============================================================================
 * main函数 - 程序的入口点
 * ============================================================================
 * 嵌入式程序的main函数通常不会返回，因为嵌入式设备没有"退出程序"的概念。
 * 所以main函数内部一定有一个 while(1) 无限循环，让程序永远运行下去。
 */
int main()
{
	/* =====================================================================
	 * 第1步：初始化LED系统
	 * =====================================================================
	 * 这行代码做了两件事（内部实现）：
	 *   a) 配置GPIO引脚模式（PB5和PE5设为推挽输出）
	 *   b) 关闭所有LED（确保上电后LED处于熄灭状态）
	 *
	 * 所有LED操作之前必须先调用这个初始化函数！
	 */
	inf_led_init();

	/* =====================================================================
	 * 第2步：测试代码（已注释）
	 * =====================================================================
	 * 下面两行是调试用的，正式运行时不执行。
	 * 在开发过程中，可以取消注释来单独测试某个功能。
	 *
	 * inf_led_open(LED1);   // 只点亮LED1，测试单个LED是否正常
	 * inf_led_open_all();   // 点亮所有LED，测试所有LED是否正常
	 */

	//  inf_led_open(LED1);
	//  inf_led_open_all();

	/* =====================================================================
	 * 第3步：创建LED数组
	 * =====================================================================
	 * 为什么要用数组？
	 *   如果只有2个LED，直接写两行代码也能实现流水灯。但用数组的好处是：
	 *   1. 代码更简洁，用for循环就能遍历所有LED
	 *   2. 如果以后增加LED3，只需在数组中加一项，循环代码不用改
	 *
	 * sizeof(leds) / sizeof(leds[0]) 是计算数组元素个数的常用技巧：
	 *   sizeof(leds)      = 数组占用的总字节数
	 *   sizeof(leds[0])   = 单个元素占用的字节数
	 *   两者相除 = 元素个数
	 *   这里 led_count = 2（两个LED）
	 */
	LedNum_t leds[] = {LED1, LED2};						// 定义LED数组，包含LED1和LED2
	uint8_t led_count = sizeof(leds) / sizeof(leds[0]); // 计算数组中有几个LED（=2）

	/* =====================================================================
	 * 第4步：主循环 - 流水灯效果
	 * =====================================================================
	 * while(1) 是无限循环，条件永远为真，程序会一直在这里运行。
	 * 嵌入式程序开机后就要一直工作，所以需要无限循环。
	 */
	while (1)
	{
		/* ------------------------------------------------------------------
		 * 流水灯方式1（已注释）：逐个点亮，始终只有一个灯亮
		 * ------------------------------------------------------------------
		 * 效果：先关所有灯 -> 亮LED1 -> 延时0.5秒 -> 关所有灯 -> 亮LED2 -> ...
		 * 特点：任意时刻只有一个灯亮，上一个灯不会自动灭
		 *
		 * 代码：
		 * for (uint8_t i = 0; i < led_count; i++)
		 * {
		 *     inf_led_close_all();    // 先关掉所有灯
		 *     inf_led_open(leds[i]);  // 再点亮当前这个灯
		 *     common_delay_ms(500);   // 等待0.5秒
		 * }
		 */

		/* ------------------------------------------------------------------
		 * 流水灯方式2（当前使用）：每个灯亮一下然后灭，依次进行
		 * ------------------------------------------------------------------
		 * 效果：LED1亮0.5秒 -> LED1灭 -> LED2亮0.5秒 -> LED2灭 -> 循环
		 * 特点：每个灯亮完自己会灭，下一个灯才亮，形成"跑马灯"效果
		 *
		 * for循环执行过程（第一次循环 i=0 时）：
		 *   inf_led_open(leds[0])   -> 点亮LED1（PB5输出0，LED亮）
		 *   common_delay_ms(500)    -> 等待500毫秒（0.5秒），让LED1亮一会儿
		 *   inf_led_close(leds[0])  -> 关闭LED1（PB5输出1，LED灭）
		 *
		 * 第二次循环 i=1 时，操作LED2，过程相同。
		 * 循环结束后 i 回到 0，无限重复。
		 */
		for (uint8_t i = 0; i < led_count; i++) // i 从 0 到 1，依次操作每个LED
		{
			inf_led_open(leds[i]);	// 点亮当前LED（leds[i] 就是 LED1 或 LED2）
			common_delay_ms(500);	// 延时500毫秒 = 0.5秒，让人眼看到灯亮
			inf_led_close(leds[i]); // 关闭当前LED，准备下一个灯亮
		}
	}
}