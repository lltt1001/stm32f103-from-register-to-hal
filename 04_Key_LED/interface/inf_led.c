#include "inf_led.h"

/**
 * @brief 初始化LED系统
 * 
 * 【执行流程】
 * ---------------------------------------------------------------------------
 * 1. DRI_LED_GPIO_Init() - 调用驱动层GPIO初始化函数
 *    - 配置PB5和PE5为推挽输出模式
 *    - 使能GPIOB和GPIOE的时钟（RCC_APB2ENR寄存器）
 *    - 设置引脚速度、上下拉等参数
 * 
 * 2. inf_led_close_all() - 关闭所有LED
 *    - 确保上电后LED处于熄灭状态，避免乱闪
 *    - 让系统从一个已知的初始状态开始运行
 * 
 * 【为什么不需要传参数？】
 * ---------------------------------------------------------------------------
 * 因为初始化是全局操作，不需要指定具体哪个LED
 * 内部会自动处理所有LED（通过led_map数组）
 * 
 * 使用示例：
 *   int main(void) {
 *       SystemInit();
 *       inf_led_init();  // 只需调用一次，无需传参
 *       // ... 后续可以使用其他LED函数
 *   }
 */
void inf_led_init(void)
{
    DRI_LED_GPIO_Init();      // 初始化GPIO配置（标准库方式）
    inf_led_close_all();      // 关闭所有LED，设置初始状态为"全灭"
}

/**
 * @brief 点亮指定编号的LED
 * 
 * @param led LED编号（如LED1、LED2）
 * 
 * 【工作原理】
 * ---------------------------------------------------------------------------
 * 通过led_map[led]获取对应LED的端口和引脚，然后直接操作ODR寄存器：
 *   - port->ODR &= ~pin 将对应位清零，引脚输出低电平
 *   - 因为开发板LED是低电平点亮（阴极接GPIO，阳极接VCC通过限流电阻）
 *   - 所以输出低电平(0)时，LED两端有电压差，LED亮
 * 
 * 【与HAL库的区别】
 * ---------------------------------------------------------------------------
 * HAL库：HAL_GPIO_WritePin(GPIOx, GPIO_Pin, GPIO_PIN_RESET);
 * 标准库：port->ODR &= ~pin;  // 直接操作寄存器，效率更高
 * 
 * 【使用示例】
 * ---------------------------------------------------------------------------
 *   inf_led_open(LED1);  // 点亮PB5上的LED1
 *   inf_led_open(LED2);  // 点亮PE5上的LED2
 */
void inf_led_open(LedNum_t led)
{
    led_map[led].port->ODR &= ~led_map[led].pin;  // 输出低电平，LED亮
}

/**
 * @brief 关闭指定编号的LED
 * 
 * @param led LED编号（如LED1、LED2）
 * 
 * 【工作原理】
 * ---------------------------------------------------------------------------
 *   - port->ODR |= pin 将对应位置1，引脚输出高电平
 *   - 高电平时，LED两端都是高电平（阳极也是VCC），无电压差，LED熄灭
 * 
 * 【使用示例】
 * ---------------------------------------------------------------------------
 *   inf_led_close(LED1);  // 关闭PB5上的LED1
 *   inf_led_close(LED2);  // 关闭PE5上的LED2
 */
void inf_led_close(LedNum_t led)
{
    led_map[led].port->ODR |= led_map[led].pin;  // 输出高电平，LED灭
}

/**
 * @brief 关闭所有LED
 * 
 * 【工作原理】
 * ---------------------------------------------------------------------------
 * 通过遍历led_map数组，对每个LED执行关闭操作。
 * 即使LED在不同GPIO端口，也能一次性全部关闭。
 * 
 * 【循环过程详解】
 * ---------------------------------------------------------------------------
 *   i=0: led_map[0] = {GPIOB, (1<<5)}
 *        -> GPIOB->ODR |= (1<<5)
 *        -> PB5输出高电平，LED1灭
 *   
 *   i=1: led_map[1] = {GPIOE, (1<<5)}
 *        -> GPIOE->ODR |= (1<<5)
 *        -> PE5输出高电平，LED2灭
 * 
 * 【应用场景】
 * ---------------------------------------------------------------------------
 *   - 初始化时确保所有LED处于已知状态（熄灭）
 *   - 程序复位或异常时快速关闭所有LED
 *   - 切换工作模式前清空指示灯状态
 */
void inf_led_close_all(void)
{
    for (uint16_t i = 0; i < LED_NUM_MAX; i++)
    {
        // 通过数组访问每个LED的端口和引脚
        led_map[i].port->ODR |= led_map[i].pin;
    }
}

/**
 * @brief 点亮所有LED
 * 
 * 【工作原理】
 * ---------------------------------------------------------------------------
 * 与close_all()相反，将所有LED设为低电平（点亮）。
 * 
 * 【循环过程】
 * ---------------------------------------------------------------------------
 *   i=0: GPIOB->PB5输出低电平，LED1亮
 *   i=1: GPIOE->PE5输出低电平，LED2亮
 * 
 * 【应用场景】
 * ---------------------------------------------------------------------------
 *   - 测试所有LED是否正常工作（上电自检）
 *   - 实现"全亮"效果（如警报状态）
 *   - 调试时确认GPIO配置是否正确
 */
void inf_led_open_all(void)
{
    for (uint16_t i = 0; i < LED_NUM_MAX; i++)
    {
        led_map[i].port->ODR &= ~led_map[i].pin;
    }
}

/**
 * @brief 切换指定编号LED的状态（亮变灭，灭变亮）
 * 
 * @param led LED编号（如LED1、LED2）
 * 
 * 【工作原理】
 * ---------------------------------------------------------------------------
 * 使用异或运算(^=)自动翻转引脚当前状态：
 *   - 如果当前是低电平(亮) -> 翻转为高电平(灭)
 *   - 如果当前是高电平(灭) -> 翻转为低电平(亮)
 * 
 * 内部实现逻辑（简化版）：
 *   port->ODR ^= pin;
 *   等价于：
 *   if ((port->ODR & pin) == 0)
 *       port->ODR |= pin;     // 亮->灭
 *   else
 *       port->ODR &= ~pin;    // 灭->亮
 * 
 * 【应用场景】
 * ---------------------------------------------------------------------------
 *   - 实现LED闪烁效果（配合定时器或延时）
 *   - 按钮控制LED开关（每次按下翻转状态）
 *   - 状态指示（如：网络连接成功/失败交替闪烁）
 * 
 * 【使用示例】
 * ---------------------------------------------------------------------------
 *   // 实现1Hz闪烁（周期1秒）
 *   while(1) {
 *       inf_led_toggle(LED1);  // 翻转LED1
 *       common_delay_ms(500);  // 延时500ms
 *   }
 */
void inf_led_toggle(LedNum_t led)
{
    led_map[led].port->ODR ^= led_map[led].pin;  // 自动翻转引脚电平
}

